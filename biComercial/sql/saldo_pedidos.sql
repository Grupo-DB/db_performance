SELECT
CASE
 WHEN PEDFIL = 0 THEN EMPSIGLA
 ELSE FILSIGLA
END EMPRESA_FILIAL, PEDDATA DATA_CRIACAO, PEDDATAPREV DATA_PREVISTA_ENTREGA, PEDNUM PEDIDO,

CLICOD CLIENTE_CODIGO, CLINOME CLIENTE, REPNOME REPRESENTANTE, REPCOD REPRESENTANTE_CODIGO,

CASE
 WHEN PEDECLI > 0 THEN (SELECT CIDNOME + '-' + ESTUF FROM ENDERECOCLIENTE
 JOIN CIDADE ON CIDCOD = ECLICIDADE
            JOIN ESTADO ON ESTCOD = CIDEST
            WHERE ECLICOD = PEDECLI
            AND ECLICLI = PEDCLI)
 ELSE CIDNOME + '-' + ESTUF
END CIDADEUF,

CASE
 WHEN GRPCOD IS NULL THEN GALMNOME
 ELSE GRPNOME
END GRUPO,

ESTQCOD ESTOQUE_CODIGO, ESTQNOME ESTOQUE, ESPSIGLA ESPECIE,
(IPEDQUANT * IPEDPESO)/1000 QUANT_TN,
IPEDQUANT QUANT,
(IPEDQUANTDESP * IPEDPESO)/1000 QUANTDESP_TN,
IPEDQUANTDESP QUANTDESP,
(IPEDQUANTCANC * IPEDPESO)/1000 QUANTCANC_TN,
IPEDQUANTCANC QUANTCANC,
IPEDTOTAL VALOR_TOTAL,

(SELECT QESTQESTOQUE FROM QUANTESTOQUE
 WHERE QESTQESTQ = IPED.IPEDESTQ
 AND QESTQEMP = PED.PEDEMP
 AND QESTQFIL = PED.PEDFIL
 AND QESTQTIPO = NOP.NOPQETIPO
 AND QESTQREF = NOP.NOPQEREF) SALDO_ESTOQUE  -- no BI também se chamava ESTOQUE (nome repetido)

FROM ITEMPEDIDO IPED
JOIN PEDIDO PED ON IPEDPED = PED.PEDNUM
JOIN NATUREZAOPERACAO NOP ON NOPCOD = PED.PEDNOPDESP
JOIN CLIENTE ON CLICOD = PEDCLI
JOIN CIDADE ON CIDCOD = CLICIDADE
JOIN ESTADO ON ESTCOD = CIDEST
JOIN REPRESENTANTE ON REPCOD = PEDREP
JOIN ESTOQUE ON ESTQCOD = IPEDESTQ
JOIN ESPECIE ON ESPCOD = ESTQESP
JOIN GRUPOALMOXARIFADO ON GALMCOD = ESTQGALM
LEFT OUTER JOIN GRUPOPRODUTO ON GRPCOD = ESTQGRP
JOIN EMPRESA ON EMPCOD = PEDEMP
LEFT OUTER JOIN FILIAL ON FILCOD = PEDFIL

WHERE PEDSIT = 0
AND (IPEDQUANT - IPEDQUANTDESP - IPEDQUANTCANC) > 0.01
