NOPENOME + ' (' +
SUBSTRING(CAST(INFECFOP AS VARCHAR(MAX)), 1, 1) + '.' +
SUBSTRING(CAST(INFECFOP AS VARCHAR(MAX)), 2, 3) + ')' NATUREZA_OPERACAO,
