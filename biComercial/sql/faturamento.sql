-- 23/11/2026. Mudanças: período por parâmetro (parâmetros desde e ate; era fixo desde 2021), sem a
-- coluna LOCAL_CARREGAMENTO (nenhum visual usa) e com NFCOD/TIPO_NF para contar notas.
SELECT
CASE
 WHEN NFFIL = 0 THEN EMPSIGLA
 ELSE FILSIGLA
END EMPRESAFILIAL, NFDATA DATA_EMISSAO, NFNUM NOTA_FISCAL, NF.NFCOD NFCOD, 'S' TIPO_NF,
NOPNOME + ' (' +
SUBSTRING(CAST(INFCFOP AS VARCHAR(MAX)), 1, 1) + '.' +
SUBSTRING(CAST(INFCFOP AS VARCHAR(MAX)), 2, 3) + ')' NATUREZA_OPERACAO,
CLINOME CLIENTE_NOME, CLICOD CLIENTE_CODIGO, CLICNPJCPF CLIENTE_CNPJCPF,
(SELECT CIDNOME + '-' + ESTUF FROM CIDADE
 JOIN ESTADO ON ESTCOD = CIDEST
 WHERE CIDCOD = CLICIDADE) CLIENTE_CIDADE,
CASE
 WHEN (SELECT PPDADOCHAR FROM PESPARAMETRO
 WHERE PPTPP = 579 AND PPREF = INF.INFPED) = 'S' AND NFECLI > 0 THEN (SELECT CIDNOME + '-' + ESTUF FROM ENDERECOCLIENTE
 JOIN CIDADE ON CIDCOD = ECLICIDADE
 JOIN ESTADO ON ESTCOD = CIDEST
 WHERE ECLICOD = NFECLI
 AND ECLICLI = NFCLI)
 ELSE (SELECT CIDNOME + '-' + ESTUF FROM CIDADE
 JOIN ESTADO ON ESTCOD = CIDEST
 WHERE CIDCOD = CLICIDADE)
END CIDADE_FATURAMENTO,
R.REPNOME REPRESENTANTE, R.REPCOD REPRESENTANTE_CODIGO,
M.REPNOME REPRESENTANTE_MASTER, M.REPNOME REPRESENTANTE_MASTER_CODIGO,
ESTQNOME ESTOQUE, ESTQAPELIDO APELIDO, ESTQCOD ESTOQUE_CODIGO, ESPSIGLA UNIDADE,
CASE
 WHEN ESTQGRP = 0 THEN GALMNOME
 ELSE GRPNOME
END GRUPO,
CASE
 WHEN ESTQGALM IN (1587, 1828) THEN 'AGRONEGOCIO'
 ELSE 'CONSTRUCAO CIVIL'
END SEGMENTO_PRODUTO,
INFQUANT QUANTIDADE,
((INFQUANT * CASE WHEN ESTQPESO > 0 THEN ESTQPESO ELSE 1 END) / 1000) QUANTIDADE_TN,
((INFTOTAL / (NFTOTPRO+NFTOTSERV)) * (NFTOTPRO+NFTOTSERV)) VALOR_PRODUTO,
(INFICMSSTVALOR) ICMSST,
(INFDAFRETE) FRETE,
((INFTOTAL / (NFTOTPRO+NFTOTSERV)) * NFTOTAL) VALOR_TOTAL,

CASE
 WHEN NOPFLAGNF LIKE 'S_______N%' AND SUBSTRING(NOPFLAGNF, 99, 1) = 'N' THEN 'SIM'
ELSE 'NAO'
END FINANCEIRO,

CASE
 WHEN NOPFLAGNF LIKE '_S______N%' AND SUBSTRING(NOPFLAGNF, 99, 1) = 'N' THEN 'SIM'
ELSE 'NAO'
END VOLUME,
(SELECT EGCNOME FROM PESPARAMETRO PP
 JOIN RH_ESTOQUE_GRUPO_COMERCIAL ON EGCCOD = PP.PPDADOINTEGER
 WHERE PP.PPTPP = 724
 AND PP.PPREF = ESTQ.ESTQCOD) GRUPO_COMERCIAL,
CASE
 WHEN R.REPREPREF > 0 THEN M.REPNOME
 WHEN CLICOD IN (37, 2454) THEN 'YARA'
 WHEN ESTQGALM IN (1587, 1828) THEN R.REPNOME
 ELSE CASE
 WHEN (SELECT PPDADOCHAR FROM PESPARAMETRO
 WHERE PPTPP = 579 AND PPREF = INF.INFPED) = 'S' AND NFECLI > 0 THEN (SELECT RGNOME FROM ENDERECOCLIENTE
 JOIN CIDADE ON CIDCOD = ECLICIDADE
 JOIN REGIAO ON RGCOD = CIDRG
 WHERE ECLICOD = NFECLI
 AND ECLICLI = NFCLI)
 ELSE (SELECT RGNOME FROM CIDADE
 JOIN REGIAO ON RGCOD = CIDRG
 WHERE CIDCOD = CLICIDADE)
 END
END REGIAO,

CASE
 WHEN (SUBSTRING(NOPFLAGNF, 1, 1) = 'S' AND SUBSTRING(NOPFLAGNF, 25, 1) = 'N') THEN 'FATURAMENTO'
 ELSE ''
END FATURAMENTO,
CASE
 WHEN (SUBSTRING(NOPFLAGNF, 2, 1) = 'S' AND NOPCOD NOT IN (2)) THEN 'CARREGAMENTO'
 ELSE ''
END CARREGAMENTO,

(SELECT ESTUF FROM CIDADE
 JOIN ESTADO ON ESTCOD = CIDEST
 WHERE CIDCOD = CLICIDADE) UF_CLIENTE,
CASE
 WHEN (SELECT PPDADOCHAR FROM PESPARAMETRO
 WHERE PPTPP = 579 AND PPREF = INF.INFPED) = 'S' AND NFECLI > 0 THEN (SELECT ESTUF FROM ENDERECOCLIENTE
 JOIN CIDADE ON CIDCOD = ECLICIDADE
 JOIN ESTADO ON ESTCOD = CIDEST
 WHERE ECLICOD = NFECLI
 AND ECLICLI = NFCLI)
 ELSE (SELECT ESTUF FROM CIDADE
 JOIN ESTADO ON ESTCOD = CIDEST
 WHERE CIDCOD = CLICIDADE)
END UF_CLIENTE_FATURAMENTO

FROM NOTAFISCAL NF
JOIN CLIENTE ON CLICOD = NFCLI
LEFT OUTER JOIN REPRESENTANTE R ON R.REPCOD = NFREP
LEFT OUTER JOIN REPRESENTANTE M ON M.REPCOD = R.REPREPREF
JOIN ITEMNOTAFISCAL INF ON INFNFCOD = NFCOD
JOIN NATUREZAOPERACAO ON NOPCOD = INFNOP
JOIN ESTOQUE ESTQ ON ESTQCOD = INFESTQ
JOIN ESPECIE ON ESPCOD = ESTQESP
JOIN GRUPOALMOXARIFADO ON GALMCOD = ESTQGALM
LEFT OUTER JOIN GRUPOPRODUTO ON GRPCOD = ESTQGRP
JOIN EMPRESA ON EMPCOD = NFEMP
LEFT OUTER JOIN FILIAL ON FILCOD = NFFIL

WHERE NFSIT = 1
AND NFDATA >= :desde AND NFDATA < :ate
AND NFEMP = 1
AND GALMPRODVENDA = 'S'
AND ((SUBSTRING(NOPFLAGNF, 1, 1) = 'S' AND SUBSTRING(NOPFLAGNF, 25, 1) = 'N') OR --Flag Operação Finan. 'S' e Não Rep. Receita 'N'
 (SUBSTRING(NOPFLAGNF, 2, 1) = 'S' AND NOPCOD NOT IN (2)))
AND NFSNF NOT IN (8) -- Serie Acerto
AND SUBSTRING(NOPFLAGNF, 99, 1) = 'N' --Devolução de Compras

UNION ALL

SELECT
CASE
 WHEN NFEFIL = 0 THEN EMPSIGLA
 ELSE FILSIGLA
